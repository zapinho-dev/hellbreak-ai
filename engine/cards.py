from dataclasses import dataclass, field
from enum import Enum, auto


class CardType(Enum):
    MONSTER = auto()
    MINION = auto()
    ASSET = auto()
    EVENT = auto()
    LOCATION = auto()


class Aspect(Enum):
    CURSED = auto()
    DERANGED = auto()
    FERAL = auto()
    REVENANT = auto()
    VOID = auto()


@dataclass(frozen=True)
class CardDefinition:
    card_id: str
    name: str
    card_type: CardType

    cost: int = 0
    loyalty: dict[Aspect, int] = field(default_factory=list)

    combat: int | None = None
    health: int | None = None

    traits: tuple[str, ...] = ()

    # Resources generated by the card while it's in the Vault.
    blood_production: int = 0
    malice_production: int = 0
    draw_production: int = 0

    # Aspect icons provided while this card is in the Vault.
    vault_aspects: dict[Aspect, int] = field(default_factory=dict)

    # Original card ability text.
    ability_text: str = ""